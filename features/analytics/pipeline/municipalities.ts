export const TCE_MUNICIPALITIES: readonly TceMunicipality[] = municipalityNames
  .map((name, index) => ({
    code: String(index + 1).padStart(3, '0'),
    name,
  }))
  .filter((municipality) => municipality.code !== '001');

export function getTceMunicipality(code: string | undefined) {
  return TCE_MUNICIPALITIES.find((municipality) => municipality.code === code);
}
